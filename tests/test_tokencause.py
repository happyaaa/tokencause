    def test_human_diagnosis_separates_cache_accounting_from_actionable_cause(self):
        trace = tokencause.SessionTrace(
            id="cache-heavy",
            source="codex",
            title="Debug expensive agent session",
            events=[
                tokencause.SessionEvent(
                    category="search_output",
                    tokens=1200,
                    preview="src/a.py\nsrc/b.py\nsrc/c.py",
                    command="rg --files",
                    file_refs=("src/a.py", "src/b.py", "src/c.py"),
                    content_hash="search-1",
                ),
                tokencause.SessionEvent(
                    category="tool_output",
                    tokens=3000,
                    preview="large command output " * 200,
                    command="sed -n '1,260p' src/a.py",
                    file_refs=("src/a.py",),
                    content_hash="file-a-1",
                ),
                tokencause.SessionEvent(
                    category="tool_output",
                    tokens=1400,
                    preview="same file again " * 120,
                    command="sed -n '1,260p' src/a.py",
                    file_refs=("src/a.py",),
                    content_hash="file-a-2",
                ),
            ],
            usage_events=[
                tokencause.TokenUsage(
                    input_tokens=510000,
                    cached_input_tokens=500000,
                    output_tokens=2000,
                    total_tokens=512000,
                )
            ],
        )

        drivers = tokencause.build_session_trace_cost_drivers(trace)
        diagnosis = tokencause.build_human_diagnosis(trace, drivers)

        self.assertEqual(drivers[0].name, "Cache-heavy context")
        self.assertEqual(diagnosis.primary_driver, "Cache-heavy context")
        self.assertEqual(diagnosis.actionable_driver, "Long tool output")
        self.assertIn("explored too broadly", diagnosis.root_cause)
        self.assertIn("billing/accounting signal", diagnosis.billing_note)
        self.assertTrue(any("Broad exploration" in item for item in diagnosis.evidence))

