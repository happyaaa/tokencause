    def test_analysis_json_bounds_display_fields(self):
        long_context_item = "tool_output:" + ("very long browser log " * 40)
        long_error = "Traceback: " + ("same failure " * 80)
        events = [
            parse_event(
                {
                    "run_id": "r1",
                    "step": "retry_browser",
                    "model": "claude-sonnet-4",
                    "tool": "browser",
                    "cost_usd": 0.5,
                    "usage": {"input_tokens": 1200, "output_tokens": 100},
                    "context_items": [long_context_item],
                    "status": "error",
                    "error_message": long_error,
                },
                1,
            )
        ]

        payload = tokencause.analysis_to_json_dict(analyze(events), Path("trace.jsonl"), budget_usd=None)

        context_item = payload["top_events"][0]["context_items"][0]
        failure_error = payload["failures"][0]["error"]
        self.assertLessEqual(len(context_item), 160)
        self.assertLessEqual(len(failure_error), 160)
        self.assertNotEqual(context_item, long_context_item)
        self.assertNotEqual(failure_error, long_error)
        self.assertTrue(context_item.endswith("..."))
        self.assertTrue(failure_error.endswith("..."))

