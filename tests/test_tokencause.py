class TokenCauseTests(unittest.TestCase):
    def generated_by_text(self) -> str:
        return f"Generated by TokenCause {tokencause.__version__}"

    def test_module_version_matches_pyproject(self):
        pyproject = (Path(__file__).resolve().parent.parent / "pyproject.toml").read_text(encoding="utf-8")

        self.assertIn(f'version = "{tokencause.__version__}"', pyproject)

    def test_python_module_entrypoint_reports_version(self):
        result = subprocess.run(
            [sys.executable, "-m", "tokencause", "--version"],
            cwd=Path(__file__).resolve().parent.parent,
            text=True,
            capture_output=True,
            check=False,
        )
        output = result.stdout + result.stderr

        self.assertEqual(result.returncode, 0, output)
        self.assertIn(f"tokencause {tokencause.__version__}", output)

    def run_cli(self, *args: str) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, "tokencause.py", *args],
            cwd=Path(__file__).resolve().parent.parent,
            text=True,
            capture_output=True,
            check=False,
        )

